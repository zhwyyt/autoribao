def draw(name,title,nodes,edges,notes,size=(1800,1180)):
 im=Image.new('RGB',size,'white');d=ImageDraw.Draw(im)
 f=ImageFont.truetype(font,30);small=ImageFont.truetype(font,25);head=ImageFont.truetype(font,39)
 d.text((45,25),title,font=head,fill='black')
 def wrapped(txt,width,font):
  lines=[]
  for line in txt.split('\n'):
   cur=''
   for ch in line:
    if d.textlength(cur+ch,font=font)>width and cur:lines.append(cur);cur=ch
    else:cur+=ch
   lines.append(cur)
  return lines
 for key,(x,y,w,h,txt) in nodes.items():
  d.rectangle((x,y,x+w,y+h),fill='#F1F5F6',outline='#48595C',width=3)
  lines=wrapped(txt,w-28,f); yy=y+(h-len(lines)*40)/2
  for t in lines:d.text((x+(w-d.textlength(t,font=f))/2,yy),t,font=f,fill='black');yy+=40
 for pts,label in edges:
  d.line(pts,fill='#394B50',width=4)
  (ax,ay),(bx,by)=pts[-2:];v=math.atan2(by-ay, bx-ax);L=17
  d.polygon([(bx,by),(bx-L*math.cos(v-.45),by-L*math.sin(v-.45)),(bx-L*math.cos(v+.45),by-L*math.sin(v+.45))],fill='#394B50')
  if label:
   mid=pts[len(pts)//2];tw=d.textlength(label,font=small)
   d.rectangle((mid[0]+8,mid[1]-32,mid[0]+tw+18,mid[1]+2),fill='white');d.text((mid[0]+12,mid[1]-32),label,font=small,fill='black')
 y=size[1]-len(notes)*40-25
 for t in notes:d.text((45,y),t,font=small,fill='#333333');y+=40
 im.save(W/(name+'.png'))

