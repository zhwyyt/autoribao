def fields_of(data):
    if not isinstance(data,dict): return []
    rows=data.get('samples',data.get('list'))
    if isinstance(rows,list) and rows and isinstance(rows[0],dict):return sorted(set().union(*(r.keys() for r in rows if isinstance(r,dict))))
    return sorted(k for k in data if k not in ['totalReturned','returnedListLength'])

