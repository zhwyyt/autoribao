function page(name, role, purpose, text) {
  const rows = text.trim().split('\n').map(x => x.split('|').map(y => y.trim()));
  for (const r of rows) if (r.length !== 9) throw Error(`${name}: ${r.length}: ${r.join('|')}`);
  const p={name,role,purpose,rows}; pages.push(p); return p;
}
function fields(p, text) {
  for(const r of text.trim().split('\n').map(x=>x.split('|').map(y=>y.trim()))) {
    if(r.length!==9) throw Error(`${p.name}: ${r.length}: ${r}`); p.rows.push(r);
  }
}
